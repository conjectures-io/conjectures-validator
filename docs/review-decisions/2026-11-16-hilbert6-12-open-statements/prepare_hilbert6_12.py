from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

PACKET = Path(__file__).resolve().parent
DATE = "2026-11-16"
EXPECTED_TARGETS = 327
REVIEW_URL = (
    "https://github.com/conjectures-io/conjectures-validator/blob/main/"
    "docs/review-decisions/2026-11-16-hilbert6-12-open-statements/README.md"
)
BORGER_DE_SMIT = "https://arxiv.org/abs/1809.02295"
GURNEY = "https://arxiv.org/abs/1710.08674"
