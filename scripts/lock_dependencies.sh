#!/usr/bin/env bash
# Regenerate requirements-service.lock and requirements-service.hashes from pyproject.toml.
#
#   scripts/lock_dependencies.sh                                # re-resolve, moving nothing
#   scripts/lock_dependencies.sh --upgrade-package aiohttp      # move one package deliberately
#
# One resolve writes both files, so they cannot disagree about a version:
#
#   requirements-service.hashes  every package with every published file's sha256. The images
#                                and scripts/install_worker.sh install with `--require-hashes`
#                                against it, so a re-uploaded or substituted artifact fails the
#                                build instead of being installed.
#   requirements-service.lock    the same pins without hashes. What CI, scripts/bootstrap.sh and
#                                a laptop use as a constraint for an editable install, which pip
#                                refuses in hash-checking mode -- and a hash anywhere in a
#                                constraint file turns that mode on.
#
# Pins already in the hashed file are kept as preferences, so a run without --upgrade-package
# changes nothing unless pyproject.toml did. Refresh deliberately: read the upstream release
# notes, then rerun the verifier, API, container and localnet verification gates.
#
# Needs uv (https://docs.astral.sh/uv/). Not a runtime or CI dependency: only this script runs it.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

fail() {
  printf '%s\n' "$@" >&2
  exit 2
}

command -v uv >/dev/null || fail "uv is required: https://docs.astral.sh/uv/getting-started/installation/"

# Every extra an image or the worker host installs from. Not `dev`: test tooling is resolved
# fresh in CI and never ships.
EXTRAS=(service subnet db competition tracing)

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# uv reads an existing output file as the set of preferred pins. Seed it from the hashed file,
# or on the first run from the plain lock, which carries the same versions.
if [[ -f requirements-service.hashes ]]; then
  cp requirements-service.hashes "$work/hashes.txt"
else
  cp requirements-service.lock "$work/hashes.txt"
fi

extra_args=()
for extra in "${EXTRAS[@]}"; do extra_args+=(--extra "$extra"); done

# A release has to have been public for this long before a resolve may pick it. Most malicious
# uploads -- a hijacked maintainer account, a typo-squat, a compromised release pipeline -- are
# found and yanked within days; a cooldown means this lock is never the first to install one.
COOLDOWN_DAYS="${LOCK_COOLDOWN_DAYS:-14}"
cutoff="$(python3 -c 'import datetime as d, sys
print((d.datetime.now(d.UTC) - d.timedelta(days=int(sys.argv[1]))).strftime("%Y-%m-%dT%H:%M:%SZ"))' \
  "$COOLDOWN_DAYS")"

# Packages deliberately taken inside the cooldown, each with the reason. An exemption is for a
# security fix that cannot wait; remove it once the pinned release is older than the cutoff.
now="$(python3 -c 'import datetime as d; print(d.datetime.now(d.UTC).strftime("%Y-%m-%dT%H:%M:%SZ"))')"
exemptions=(
  # 2026.10.19 drops the compromised eMudhra and Comodo AAA roots (see SECURITY.md).
  "certifi=$now"
)
exemption_args=()
for exemption in "${exemptions[@]}"; do exemption_args+=(--exclude-newer-package "$exemption"); done

# --universal with the oldest supported Python: one file valid on every platform and interpreter
# pyproject.toml admits, with environment markers where a dependency is conditional (colorama
# on Windows), rather than a file that only resolves on the machine that ran this.
uv pip compile pyproject.toml "${extra_args[@]}" \
  --universal --python-version 3.11 \
  --exclude-newer "$cutoff" "${exemption_args[@]}" \
  --generate-hashes --no-header --no-annotate --quiet \
  --output-file "$work/hashes.txt" "$@"

python3 - "$work/hashes.txt" <<'PY'
import re
import sys
from pathlib import Path

resolved = Path(sys.argv[1]).read_text(encoding="utf-8")

PREAMBLE = """\
# Exact runtime dependency set for the conjectures.io service and Subnet 66 foundation.
# Generated by scripts/lock_dependencies.sh from pyproject.toml; do not edit by hand.
# Refresh deliberately after reviewing upstream release notes and rerunning the
# verifier, API, container, and localnet verification gates.
"""

hashed = PREAMBLE + "# Images install with --require-hashes against this file.\n" + resolved
# A requirement line continues with ` \` onto its `--hash=` lines; drop both.
plain = re.sub(r" \\\n(?:\s+--hash=\S+(?: \\)?\n)+", "\n", resolved)
if "--hash=" in plain:
    sys.exit("could not strip hashes from the resolved set; refusing to write a mixed lock")
plain = PREAMBLE + "# The same pins as requirements-service.hashes, without hashes.\n" + plain

Path("requirements-service.hashes").write_text(hashed, encoding="utf-8")
Path("requirements-service.lock").write_text(plain, encoding="utf-8")
PY

git --no-pager diff --stat -- requirements-service.lock requirements-service.hashes
