def test_a_target_index_parses_into_rows_joined_to_this_apis_conjecture_slug():
    row = parse_target(index(), directory="erdos-535")

    assert row.target == "erdos-535"
    assert row.reward_target_id == "fc-target:Erdos535.erdos_535"
    # The corpus's target slug and this API's conjecture slug are different naming schemes over
    # the same theorem. The join is the reward target, never the slug string.
    assert row.conjecture_slug == "erdos535-erdos-535"
    assert row.conjecture_slug != row.target
    assert row.contribution_count == 1
    assert row.contributions[0].declarations == ("Contribution.Erdos535BasicAPI.f_le",)
    assert row.contributions[0].rewarded is True


def test_an_index_that_names_a_different_target_than_its_directory_is_refused():
    """A copied rather than generated index would put contributions on the wrong conjecture."""
    with pytest.raises(ContributionsError):
        parse_target(index(target="erdos-100"), directory="erdos-535")


