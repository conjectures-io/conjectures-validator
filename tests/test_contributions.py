# --- Snapshot ----------------------------------------------------------------------------------


def snapshot(*targets, pending=(), unreadable=()) -> ContributionSnapshot:
    return ContributionSnapshot.build(
        repository=REPOSITORY,
        branch="main",
        head_commit=COMMIT,
        fetched_at=datetime(2026, 9, 3, 12, 0, tzinfo=UTC),
        targets=targets,
        pending=pending,
        unreadable=unreadable,
    )


def test_a_target_resolves_by_all_four_of_its_names():
    row = parse_target(index(), directory="erdos-535")
    built = snapshot(row)

    for name in ("erdos-535", "erdos535-erdos-535", "fc-target:Erdos535.erdos_535"):
        assert built.target(name) is row
    assert built.target(row.problem_id) is row
    assert built.target("erdos-999") is None


def test_a_contribution_resolves_by_full_id_and_by_unambiguous_prefix():
    built = snapshot(parse_target(index(), directory="erdos-535"))

    assert built.contribution("a" * 64) is not None
    assert built.contribution("a" * 12) is not None
    # Too short to be an identifier rather than a scan.
    assert built.contribution("aaaa") is None


def test_an_ambiguous_prefix_resolves_to_nothing_rather_than_to_the_first_match():
    built = snapshot(
        parse_target(
            index(
                contributions=(
                    entry(contribution_id="ab" + "1" * 62),
                    entry(contribution_id="ab" + "2" * 62),
                )
            ),
            directory="erdos-535",
        )
    )

    assert built.contribution("ab" + "1" * 62) is not None
    assert built.contribution("ab123456") is None


def test_the_author_cross_cut_reports_a_coldkey_two_signing_keys_share():
    built = snapshot(
        parse_target(
            index(
                contributions=(
                    entry(contribution_id="a" * 64, author=AUTHOR),
                    entry(contribution_id="b" * 64, author=OTHER_AUTHOR),
                )
            ),
            directory="erdos-535",
        )
    )

    assert {row.author for row in built.authors} == {AUTHOR, OTHER_AUTHOR}
    assert all(row.shared_coldkey for row in built.authors)


def test_an_unfetched_snapshot_is_not_an_empty_one():
    """The distinction the endpoints spend a 503 on."""
    assert ContributionSnapshot.empty(repository=REPOSITORY).available is False
