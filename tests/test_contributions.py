# --- The GitHub mirror -------------------------------------------------------------------------


def tarball(indexes: dict[str, dict], pages: dict[str, str] | None = None) -> bytes:
    """An archive shaped exactly like GitHub's: one wrapper directory over the repository."""
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as bundle:
        for target, payload in indexes.items():
            _add(bundle, f"repo-sha/contributions/{target}/index.json", json.dumps(payload))
        for target, page in (pages or {}).items():
            _add(bundle, f"repo-sha/contributions/{target}/index.md", page)
    return buffer.getvalue()


def _add(bundle: tarfile.TarFile, name: str, text: str) -> None:
    raw = text.encode("utf-8")
    info = tarfile.TarInfo(name)
    info.size = len(raw)
    bundle.addfile(info, io.BytesIO(raw))


class FakeGitHub:
    """A transport standing in for the REST API, counting what it was actually asked for."""

    def __init__(
        self,
        *,
        commit: str = COMMIT,
        archive: bytes | None = None,
        pulls: list | None = None,
    ) -> None:
        self.commit = commit
        self.archive = archive if archive is not None else tarball({"erdos-535": index()})
        self.pulls = pulls if pulls is not None else []
        self.requests: list[str] = []
        self.commit_etag = "W/\"commit-1\""
        self.pulls_etag = "W/\"pulls-1\""

    def handler(self, request: httpx.Request) -> httpx.Response:
        path = request.url.path
        self.requests.append(path)
        conditional = request.headers.get("if-none-match")
        if path.endswith("/commits/main"):
            if conditional == self.commit_etag:
                return httpx.Response(304, headers={"ETag": self.commit_etag})
            return httpx.Response(
                200, json={"sha": self.commit}, headers={"ETag": self.commit_etag}
            )
        if path.endswith("/pulls"):
            if conditional == self.pulls_etag:
                return httpx.Response(304, headers={"ETag": self.pulls_etag})
            return httpx.Response(
                200, json=self.pulls, headers={"ETag": self.pulls_etag}
            )
        if "/tarball/" in path:
            return httpx.Response(200, content=self.archive)
        return httpx.Response(404, json={"message": "Not Found"})


def mirror(github: FakeGitHub, **kwargs) -> GitHubContributionMirror:
    return GitHubContributionMirror(
        repository=REPOSITORY,
        api_base_url="https://api.github.test",
        client=httpx.AsyncClient(
            transport=httpx.MockTransport(github.handler),
            base_url="https://api.github.test",
        ),
        **kwargs,
    )


def test_a_first_poll_reads_the_whole_corpus_from_one_archive():
    github = FakeGitHub(
        archive=tarball(
            {"erdos-535": index()},
            pages={
                "erdos-1049": PAGE.format(
                    target="erdos-1049", theorem="Erdos1049.erdos_1049"
                )
            },
        )
    )
    subject = mirror(github)

    assert run(subject.refresh()) is True
    built = subject.snapshot()

    assert built.head_commit == COMMIT
    assert len(built.targets) == 2
    assert len(built.contributions) == 1
    assert built.target("erdos-1049").contribution_count == 0
    assert sum(1 for path in github.requests if "tarball" in path) == 1
    run(subject.aclose())


def test_a_poll_where_nothing_moved_costs_two_conditional_requests_and_no_archive():
    """The steady state. A 304 does not count against GitHub's hourly budget."""
    github = FakeGitHub()
    subject = mirror(github)
    run(subject.refresh())
    github.requests.clear()

    assert run(subject.refresh()) is False
    assert [path.rsplit("/", 1)[-1] for path in github.requests] == ["main", "pulls"]
    run(subject.aclose())


def test_a_moved_head_rebuilds_the_snapshot():
    github = FakeGitHub()
    subject = mirror(github)
    run(subject.refresh())

    github.commit = OTHER_COMMIT
    github.commit_etag = 'W/"commit-2"'
    github.archive = tarball({"erdos-535": index(), "erdos-100": index(target="erdos-100")})

    assert run(subject.refresh()) is True
    assert subject.snapshot().head_commit == OTHER_COMMIT
    assert len(subject.snapshot().targets) == 2
    run(subject.aclose())


def test_a_failed_poll_leaves_the_previous_snapshot_serving():
    """A stale corpus is a far better answer than an empty one."""
    github = FakeGitHub()
    subject = mirror(github)
    run(subject.refresh())
    good = subject.snapshot()

    github.commit_etag = 'W/"commit-2"'
    github.archive = b"not a tarball"

    assert run(subject.refresh()) is False
    assert subject.snapshot() is good
    assert subject.snapshot().available is True
    run(subject.aclose())


def test_a_failed_first_load_is_retried_rather_than_answered_304_forever():
    """The bug conditional requests invite: caching a validator for a commit that never loaded.

    The head fetch succeeds, the archive read fails. If the head `ETag` were stored anyway, every
    later poll would be told `304`, the mirror would never attempt that commit again, and it would
    sit unavailable indefinitely while looking like a healthy quiet loop.
    """
    github = FakeGitHub(archive=b"not a tarball")
    subject = mirror(github)

    assert run(subject.refresh()) is False
    assert subject.snapshot().available is False

    github.archive = tarball({"erdos-535": index()})
    assert run(subject.refresh()) is True
    assert subject.snapshot().available is True
    run(subject.aclose())


def test_a_commit_whose_archive_failed_is_retried_without_waiting_for_a_new_commit():
    """The same trap one state later: a good snapshot serving, and a new commit that would not load."""
    github = FakeGitHub()
    subject = mirror(github)
    run(subject.refresh())

    github.commit = OTHER_COMMIT
    github.commit_etag = 'W/"commit-2"'
    github.archive = b"not a tarball"
    assert run(subject.refresh()) is False
    assert subject.snapshot().head_commit == COMMIT

    github.archive = tarball({"erdos-535": index(), "erdos-100": index(target="erdos-100")})
    assert run(subject.refresh()) is True
    assert subject.snapshot().head_commit == OTHER_COMMIT
    run(subject.aclose())


