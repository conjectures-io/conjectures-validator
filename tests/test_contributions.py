"""The contribution corpus model and the GitHub mirror that fills it.

No network and no database. `submission_api/contributions.py` is pure, and the mirror is driven
through an injected `httpx` transport that serves a tarball built in memory — so the archive
walk, the conditional-request bookkeeping and the rate-limit backoff are all exercised against
the same code paths that talk to github.com, without talking to it.

The HTTP surface is `tests/test_api_contributions.py`.
"""

