def run(coroutine):
    return asyncio.run(coroutine)


def entry(
    *,
    contribution_id: str = "a" * 64,
    author: str = AUTHOR,
    added: str = "2026-09-03",
    kind: str = "lemma",
    mode: str = "formalized",
    title: str = "Extremal witness and monotonicity API",
    declarations: tuple[str, ...] = ("Contribution.Erdos535BasicAPI.f_le",),
    coldkey: str | None = COLDKEY,
    hotkey: str | None = HOTKEY,
) -> dict:
    return {
        "added": added,
        "artifacts": ["script.lean", "sources.md"],
        "author": author,
        "coldkey": coldkey,
        "contribution_id": contribution_id,
        "declarations": list(declarations),
        "hotkey": hotkey,
        "kind": kind,
        "mode": mode,
        "parents": [],
        "path": f"{contribution_id}/",
        "tasks_commit": "379fc0298dc146df549e7061c3ede0353a5bb51f",
        "title": title,
    }


def index(
    *,
    target: str = "erdos-535",
    reward_target_id: str | None = "fc-target:Erdos535.erdos_535",
    contributions: tuple[dict, ...] | None = None,
    open_: bool = True,
) -> dict:
    return {
        "contribution_count": len(contributions or (entry(),)),
        "contributions": list(contributions if contributions is not None else (entry(),)),
        "open": open_,
        "problem_id": f"fc-379fc029-{target}-problem",
        "reward_target_id": reward_target_id,
        "schema_version": 2,
        "target": target,
    }


PAGE = (
    "# {target}\n\n"
    "<!-- Generated by `contrib-admin index`. Do not edit by hand. -->\n\n"
    "**Problem** `fc-379fc029-{target}-problem` · "
    "**Reward target** `fc-target:{theorem}`\n"
)


