def test_a_rate_limit_refusal_backs_off_instead_of_retrying_into_the_penalty_box():
    clock = [0.0]

    class Throttled(FakeGitHub):
        def handler(self, request):
            self.requests.append(request.url.path)
            return httpx.Response(
                403,
                headers={"x-ratelimit-remaining": "0", "retry-after": "120"},
                json={"message": "rate limit exceeded"},
            )

    github = Throttled()
    subject = mirror(github, monotonic=lambda: clock[0])

    assert run(subject.refresh()) is False
    assert len(github.requests) == 1

    # Still inside the backoff: no request is made at all.
    clock[0] = 60.0
    assert run(subject.refresh()) is False
    assert len(github.requests) == 1

    clock[0] = 200.0
    assert run(subject.refresh()) is False
    assert len(github.requests) == 2
    run(subject.aclose())


